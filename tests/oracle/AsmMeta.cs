// The instruction docs the disassembler's hover popup shows (AutoDocs/MetaInfo/ASMMetaInfo) as a C++ include.
//
//   dotnet run -c Release -- --asmmeta <out.inc>      -> src/service/asm_meta.inc
using System.Text;
using Continuum93.Emulator.AutoDocs.MetaInfo;

static class AsmMeta
{
    public static int Run(string outPath)
    {
        ASMMetaInfo.DeInitialize();
        ASMMetaInfo.Initialize();
        var w = new StringBuilder();
        w.Append("// Generated by tests/oracle --asmmeta from the reference's ASMMetaInfo. Do not edit: regenerate.\n");
        w.Append("// {operators (space separated), Description, Application, Format}, in the reference's order (first match wins)\n");
        w.Append("static const AsmMeta kAsmMeta[] = {\n");
        foreach (ASMMeta m in ASMMetaInfo.MetaData)
            w.Append($"  {{{Q(string.Join(" ", m.Operators))},\n   {Q(m.Description)},\n   {Q(m.Application)},\n   {Q(m.Format)}}},\n");
        w.Append("};\n");
        File.WriteAllText(outPath, w.ToString());
        Console.WriteLine($"asmmeta: {ASMMetaInfo.MetaData.Count} entries -> {outPath}");
        return 0;
    }

    static string Q(string s)
    {
        if (s == null) return "nullptr";
        foreach (char c in s) if (c > 0x7E || (c < 0x20)) throw new Exception($"non-ASCII char U+{(int)c:X4} in ASMMetaInfo");
        return "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }
}
