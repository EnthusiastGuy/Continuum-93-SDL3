// Assembler vectors and the generated encoding table for src/asm.cpp.
//
//   dotnet run -c Release -- --optable <out.inc>      Mnem.OPS + register/flag names as a C++ include
//   dotnet run -c Release -- --asm <dir>... <out.txt> every .asm/.c under the dirs, assembled by the reference
//
// --asm output per file (numbers hex):
//   F <path>              an .asm file, assembled from disk (the C++ side reads it and its includes)
//   C <path>              a .c file: the reference C compiler's output follows, UTF-8 as hex
//   S <hex>
//   R <errors> <run address>
//   L <line>              a line the reference counted as an error
//   B <start> <bytes>     one line per code block
//   X <exception>         the reference threw while assembling (no R/L/B lines)
//   T <microseconds>      best of 5 builds (timing only)
using System.Diagnostics;
using System.Text;
using Continuum93.Emulator;
using Continuum93.Emulator.Compilers.C93C;
using Continuum93.Emulator.Interpreter;
using Continuum93.Emulator.Mnemonics;

static class Asm
{
    public static int OpTable(string outPath)
    {
        var w = new StringBuilder();
        w.Append("// Generated by tests/oracle --optable from the reference's Mnem.OPS, Mnem.REG, Mnem.SREG and\n");
        w.Append("// Flags names. Do not edit: regenerate.\n");
        w.Append("// {key, primary, code (OpCode if primary, else ParentCode), sub-op (OpCodes[0], -1 if primary), format}\n");
        w.Append("static const AsmOp kOps[] = {\n");
        foreach (var (key, op) in Mnem.OPS)   // insertion order, as the reference built it
            w.Append($"  {{{Q(key)}, {(op.IsPrimary ? 1 : 0)}, {(op.IsPrimary ? op.OpCode : op.ParentCode ?? 0)}, {(op.IsPrimary ? -1 : op.OpCodes[0])}, {Q(op.Format ?? "")}}},\n");
        w.Append("};\n\n// General-purpose registers: name -> index\nstatic const AsmName kRegs[] = {\n");
        foreach (var (name, i) in Mnem.REG) w.Append($"  {{{Q(name)}, {i}}},\n");
        w.Append("};\n\n// Flag names -> index (Flags.GetFlagIndexByName)\nstatic const AsmName kFlags[] = {\n");
        for (byte i = 0; i < 255; i++) { string n = Flags.GetFlagNameByIndex(i); if (n != "") w.Append($"  {{{Q(n)}, {i}}},\n"); }
        w.Append("};\n\n// Special registers (Mnem.SREG)\nstatic const char* const kSpecialRegs[] = {");
        w.Append(string.Join(", ", Mnem.SREG.Select(Q)));
        w.Append("};\n");
        File.WriteAllText(outPath, w.ToString().Replace("\r\n", "\n"));
        Console.WriteLine($"optable: {Mnem.OPS.Count} ops, {Mnem.REG.Count} registers -> {outPath}");
        return 0;
    }

    static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    public static int Run(string[] dirs, string outPath)
    {
        using var w = new StreamWriter(outPath) { NewLine = "\n" };
        int n = 0, threw = 0;
        foreach (string path in dirs.SelectMany(d => Directory.GetFiles(d, "*", SearchOption.AllDirectories).Where(p => p.EndsWith(".asm") || p.EndsWith(".c")).Order(StringComparer.Ordinal)))
        {
            if (path.Contains(Path.DirectorySeparatorChar + "debug" + Path.DirectorySeparatorChar)) continue;   // the reference's own build output
            string src = File.ReadAllText(path), full = Path.GetFullPath(path), asmPath = full;
            if (path.EndsWith(".c"))
            {
                string cdir = Path.GetDirectoryName(full);
                var cc = new CCompiler
                {
                    IncludeResolver = (name, including) =>
                    {
                        string c = Path.Combine(cdir, Path.GetDirectoryName(including) ?? "", name);
                        if (!File.Exists(c)) c = Path.Combine(cdir, name);
                        return File.Exists(c) ? File.ReadAllText(c) : null;
                    }
                };
                src = cc.Compile(src, Path.GetFileName(full));
                if (cc.Errors > 0) { Console.Error.WriteLine($"asm: {full}: C compile failed ({cc.ErrorList[0]}), skipped"); continue; }
                w.WriteLine($"C {full}");
                w.WriteLine($"S {Convert.ToHexString(Encoding.UTF8.GetBytes(src))}");
                asmPath = "";   // generated code has no includes; the C++ side assembles the text as is
            }
            else w.WriteLine($"F {full}");

            CompileLog.Reset();
            var asm = new Assembler();
            try { asm.Build(src, asmPath); }
            catch (Exception e) { w.WriteLine($"X {e.GetType().Name}: {e.Message.Replace('\n', ' ').Replace('\r', ' ')}"); threw++; n++; continue; }
            w.WriteLine($"R {asm.Errors:X} {asm.GetRunAddress():X}");
            for (int i = 0; asm.GetCompiledLine(i) is CLine l; i++) if (l.Error != null) w.WriteLine($"L {l.LineNr:X}");
            foreach (var b in asm.BlockManager.GetBlocks()) w.WriteLine($"B {b.Start:X} {Convert.ToHexString(b.Data ?? [])}");
            if (full.EndsWith("q.asm") || full.EndsWith("halcyon.c"))   // boot-time builds
            {
                long best = long.MaxValue;
                for (int k = 0; k < 5; k++)
                {
                    CompileLog.Reset();
                    var sw = Stopwatch.StartNew();
                    new Assembler().Build(src, asmPath);
                    best = Math.Min(best, sw.Elapsed.Ticks / 10);
                }
                w.WriteLine($"T {best:X}");
                Console.WriteLine($"asm: {Path.GetFileName(full)} best of 5: {best / 1000.0:F1} ms");
            }
            n++;
        }
        Console.WriteLine($"asm: {n} files ({threw} threw) -> {outPath}");
        return 0;
    }
}
