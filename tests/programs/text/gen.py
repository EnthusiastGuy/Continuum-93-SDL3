def db(label, data):
    out = [f".{label}"]
    for i in range(0, len(data), 32):
        out.append("    #DB " + ", ".join(f"0x{b:02X}" for b in data[i:i + 32]))
    if not data:
        out.append("    #DB 0x00")
    return out


class Prog:
    def __init__(self, name, steps=20000):
        self.name, self.steps, self.code, self.data, self.slots = name, steps, [], [], 0

    def call(self, fn, reg, params, store=(0, 4)):
        """params: list of (offset, width_bits, value) or (offset, width, label)."""
        r = R.index(reg)
        regs = {}
        labels = []
        for off, w, v in params:
            if isinstance(v, str):
                labels.append((off, w, v))
                continue
            v &= (1 << w) - 1
            for k in range(w // 8):
                regs[(r + off + k) % 26] = (v >> (w - 8 * (k + 1))) & 0xFF
        regs[r] = fn
        for i, v in regs.items():
            self.code.append(f"    LD {R[i]}, 0x{v:02X}")
        for off, w, lab in labels:   # 24-bit label loads (no wrap in our usage)
            names = "".join(R[(r + off + k) % 26] for k in range(3))
            self.code.append(f"    LD {names}, .{lab}")
        self.code.append(f"    LD {R[r]}, 0x{fn:02X}")
        self.code.append(f"    INT 0x01, {R[r]}")
        if store:
            off, n = store
            for part in range(0, n, 4):
                names = "".join(R[(r + off + part + k) % 26] for k in range(4))
                lab = f"S{self.slots}"
                self.slots += 1
                self.code.append(f"    LD (.{lab}), {names}")
                self.data += db(lab, [0xEE] * 4)

    def write(self):
        lines = [f"; steps: {self.steps}", f"; {self.name}: generated by gen_text_tests.py", "#ORG 0x080000"]
        lines += self.code + ["    BREAK", ""] + self.data
        open(os.path.join(OUT, self.name + ".asm"), "w", newline="\n").write("\n".join(lines) + "\n")


