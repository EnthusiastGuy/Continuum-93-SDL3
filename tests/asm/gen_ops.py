# Writes tests/asm/ops.asm: every instruction variant in src/asm_ops.inc, three times with varied operands
# (register runs, number spellings, labels, offsets, flags, mixed case). Deterministic (seed 93).
#   python tests/asm/gen_ops.py
import os, random, re

here = os.path.dirname(os.path.abspath(__file__))
inc = open(os.path.join(here, '..', '..', 'src', 'asm_ops.inc'), encoding='utf-8').read()
keys = [k for k, primary in re.findall(r'\{"([^"]+)", (\d), ', inc.split('kRegs')[0]) if primary == '0']
regs = re.findall(r'\{"([A-Z]+)", \d+\}', inc.split('kRegs')[1].split('};')[0])
flags = re.findall(r'\{"([A-Z]+)", \d+\}', inc.split('kFlags')[1].split('};')[0])
rnd = random.Random(93)
labels = ['.Start', '.data_1', '.Far?', '.loop']

def num(bits, allow_label=False):
    v = rnd.randrange(1 << bits)
    k = rnd.randrange(8)
    if allow_label and k == 0: return rnd.choice(labels)
    if k == 1: return f'0x{v:X}'
    if k == 2: return f'0b{v & 0xFF:b}'
    if k == 3: return f'0o{v & 0x1FF:o}'
    if k == 4: return f'-{rnd.randrange(1, 100)}'
    if k == 5: return f'0x{v:0{(bits + 3) // 4}x}'
    return str(v)

def operand(t):
    if t in ('r', 'rr', 'rrr', 'rrrr'): return rnd.choice([r for r in regs if len(r) == len(t)])
    if t == 'fr': return f'F{rnd.randrange(16)}'
    if t == 'ff': return rnd.choice(flags)
    if t == 'n': return num(8)
    if t == 'nn': return num(16)
    if t == 'nnn': return num(24, True)
    if t == 'nnnn': return rnd.choice([num(32), '1.5', '-2.25', '0.1', '3.0E5', '100'])
    if t == '(nnn)': return f'({num(24, True).lstrip("-")})' if rnd.randrange(3) else f'({rnd.choice(labels)})'
    if t == '(rrr)': return f'({operand("rrr")})'
    return t   # SPC, SPR, IPO

def offset(a, b):   # "(rrr" + "nnn)" -> "(ABC + 5)"
    inner = a[1:]
    tail = b[:-1]
    first = operand(inner).lstrip('-') if inner != 'nnn' else rnd.choice(labels + [f'0x{rnd.randrange(1 << 24):X}', str(rnd.randrange(1 << 24))])   # '(-5' throws
    if tail == 'nnn': return f'({first} {rnd.choice("+-")} {rnd.randrange(1, 300)})'
    return f'({first} {"+" if rnd.randrange(4) else "-"} {operand(tail)})'

out = ['; Generated by gen_ops.py: every variant of src/asm_ops.inc, three times.', '#ORG 0x080000', '.Start']
for key in keys:
    op, _, form = key.partition(' ')
    toks = form.split(',') if form else []
    for _ in range(3):
        args, i = [], 0
        while i < len(toks):
            if toks[i].startswith('(') and not toks[i].endswith(')'):
                args.append(offset(toks[i], toks[i + 1])); i += 2
            else:
                args.append(operand(toks[i])); i += 1
        line = op + (' ' + ', '.join(args) if args else '')
        if rnd.randrange(5) == 0: line = line.lower()
        out.append(('\t' if rnd.randrange(2) else '    ') + line)
    if key == keys[len(keys) // 2]: out.append('.loop')
out += ['.data_1', '    #DB 1, 2, 3', '.Far?', '    #DB "end"', '']
open(os.path.join(here, 'ops.asm'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(f'ops.asm: {len(keys)} variants')
