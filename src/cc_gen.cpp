CcResult compileC(std::string_view source, const std::string& fileName, const CcIncludeResolver& resolve) {
    using namespace cc;
    CcResult r;
    Errors& errors = r.errors;
    std::string asmText;
    Arena a;
    auto resolveInclude = [&](const std::string& name, const std::string& including) -> std::optional<std::string> {
        for (const CcHeader& h : kCcHeaders) if (name == h.name) return std::string(h.text);
        return resolve ? resolve(name, including) : std::nullopt;
    };
    try {
        Preprocessor pp(a.files, a.tokens, resolveInclude, errors);
        TokenList& tokens = a.tokenLists.emplace_back(pp.process(source, fileName));
        if (!errors.empty()) throw Abort{};
        r.log += "Preprocessed " + fileName + ": " + std::to_string(tokens.size()) + " tokens\n";
        // "#pragma c93 origin N" / "stack N": system software (boot loader, OS) lives outside the program area
        for (auto& [name, tok] : pp.pragmas) {
            if (name != "origin" && name != "stack") continue;
            uint32_t value; bool uns; std::string err;
            if (tok.kind != TK::Number || !tryParseInt(tok.text, value, uns, err) || value > 0xFFFFFF) {
                errors.push_back({*tok.file, tok.line, tok.col, "#pragma c93 " + name + " expects a 24-bit address"});
                throw Abort{};
            }
            (name == "origin" ? r.origin : r.stackTop) = value;
        }
        Unit unit;
        TokenList& lib = a.tokenLists.emplace_back();
        ParseResult pr = parse(a, unit, errors, tokens, lib, [&] {
            // The runtime library is parsed into the same unit; user definitions take precedence
            Preprocessor libPp(a.files, a.tokens, resolveInclude, errors);
            lib = libPp.process(kCcLibrary, "<runtime>");
            if (!errors.empty()) throw Abort{};
        });
        checkProgram(unit, pr.main, fileName, errors);
        asmText = CodeGen(errors, pr.labelCounter).generate(unit, r.origin, r.stackTop);
        r.log += "Compiled " + std::to_string(unit.functions.size()) + " function(s), " + std::to_string(unit.globals.size()) +
                 " global(s), " + std::to_string(unit.strings.size()) + " string literal(s)\n";
    } catch (const Abort&) {
        // errors already recorded
    } catch (const Fatal& f) {
        r.fatal = f.what;
        return r;
    }
    for (const CcError& e : errors) r.log += e.file + ":" + std::to_string(e.line) + ":" + std::to_string(e.col) + ": error: " + e.message + "\n";
    if (errors.empty()) r.asmText = std::move(asmText);
    return r;
}

